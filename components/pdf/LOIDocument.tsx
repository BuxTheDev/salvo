function Band({ title }: { title: string }) {
  return (
    <View style={st.band}>
      <View>
        <Text style={st.brand}>BRIGHTPATH</Text>
        <Text style={st.brandSub}>BrightPath Real Estate Solutions, LLC</Text>
      </View>
      <Text style={st.docTitle}>{title}</Text>
    </View>
  );
}

function Meta({ f }: { f: LOIFields }) {
  return (
    <View style={st.meta}>
      <View style={st.metaRow}><Text style={st.metaKey}>Date</Text><Text style={st.metaVal}>{f.date}</Text></View>
      <View style={st.metaRow}><Text style={st.metaKey}>To</Text><Text style={st.metaVal}>{f.ownerFullName}</Text></View>
      <View style={st.metaRow}><Text style={st.metaKey}>Re</Text><Text style={st.metaVal}>{f.address}</Text></View>
    </View>
  );
}

function Row({ k, v, last = false }: { k: string; v: string; last?: boolean }) {
  return (
    <View style={last ? [st.row, st.rowLast] : st.row}>
      <Text style={st.cellKey}>{k}</Text>
      <Text style={st.cellVal}>{v}</Text>
    </View>
  );
}

function Footer() {
  return (
    <Text style={st.foot} fixed>
      {BUYER_ENTITY} · This Letter of Intent is non-binding and is an invitation to negotiate only. Generated by Salvo.
    </Text>
  );
}

