export interface LOIEntry {
  f: LOIFields;
  creativeOK: boolean;
  cashOK: boolean;
}

/**
 * One document for the whole selection. Creative sends can carry the cash page
 * along (the current .docx behavior) — configurable via `includeCashPage`.
 */
export function LOIDocument({ entries, offer, includeCashPage }: {
  entries: LOIEntry[];
  offer: Offer;
  includeCashPage: boolean;
}) {
  return (
    <Document title="Salvo LOIs" author={BUYER_ENTITY}>
      {entries.flatMap((e, i) => {
        const pages = [];
        const wantCreative = offer !== "cash" && e.creativeOK;
        const wantCash =
          offer === "cash" ? e.cashOK
          : offer === "both" ? e.cashOK
          : includeCashPage && e.cashOK;
        if (wantCreative) pages.push(<CreativeLOIPage key={`cr-${i}`} f={e.f} />);
        if (wantCash) pages.push(<CashLOIPage key={`ca-${i}`} f={e.f} />);
        return pages;
      })}
    </Document>
  );
}
